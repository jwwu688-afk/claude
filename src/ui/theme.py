# =============================================================================
# 文件：src/ui/theme.py
# 作用：整个界面的"配色和符号"都集中在这里
#
# 为什么单独搞一个文件？
#   之前颜色散落在各个文件里：有的用 print 打 emoji，有的用 rich 打颜色，
#   想统一风格就得改七八个地方。现在所有颜色、符号、缩进都从这一份定义里取。
#
# 【2026-11-06 第 7 轮】按 Claude Code 2.1 的实际配色重做：
#   - 主色改成 Claude 品牌橙 #D97757（Claude Code 内部把这个颜色就叫 "claude"）
#   - 去掉上一轮那套彩虹渐变，因为 Claude Code 本身是"黑白灰 + 一个橙+ 少量红绿"
#   - 输入提示符从 ❯ 改成 >
#   - 圆点 ⏺ 改成白色（Claude Code 里它不是彩色的）
# =============================================================================

from rich.console import Console  # rich 的控制台对象
from rich.theme import Theme  # 主题：给"样式名"起别名，后面用名字引用颜色

# --- 颜色 -------------------------------------------------------------------
# Claude Code 的配色非常克制：绝大多数文字是默认白/灰，只有三处上色：
#   ✻ 标志和强调 → 品牌橙；成功/新增 → 绿；失败/删除 → 红
ACCENT = "rgb(217,119,87)"  # Claude 品牌橙 #D97757，用于 ✻ 和输入提示符
DIM = "bright_black"  # 次要信息：路径、参数、状态行
OK = "green"  # 成功
ERR = "red"  # 失败
WARN = "yellow"  # 警告（只在上文快满时用）

# --- 符号 -------------------------------------------------------------------
# 这几个符号是 Claude Code 的辨识度所在，别随便换：
BULLET = "⏺"  # 模型发言 / 工具调用的起始标记（Claude Code 里是白色）
RESULT = "⎿"  # 结果的转折标记
PROMPT = ">"  # 输入提示符（Claude Code 用的是 >）
STAR = "✻"  # 品牌标志 / 等待动画
CHECK_ON = "✔"  # 已完成
CHECK_OFF = "◻"  # 未完成
CHECK_RUN = "◼"  # 进行中
CROSS = "✗"  # 失败
DOT = "·"  # 分隔点
WARN_SIGN = "!"  # 【第 9 轮】警告标记（高危操作确认前提示用）

# 等待模型时的旋转图案：用大小不同的星芒，转起来像在"扫描"
SPIN_FRAMES = ["✻", "✢", "✳", "✶", "✻", "✢", "✳", "✶"]

# 全局唯一的一个控制台对象。
# 之前每个类都 new 一个 Console，导致样式各写各的；现在大家共用这一个。
console = Console(
    theme=Theme({
        "qs.accent": ACCENT,
        "qs.dim": DIM,
        "qs.ok": OK,
        "qs.err": ERR,
        "qs.warn": WARN,
    }),
    highlight=False,  # 关掉自动高亮，避免把普通文字里的数字、路径染成奇怪的颜色
    # 【第 7 轮】关掉 safe_box：rich 默认在"看起来不像真终端"时用 ┌─┐ 代替圆角 ╭─╮，
    #   导致同一个界面在终端里是圆角、重定向到文件时变方角。这里统一成圆角。
    safe_box=False,
)

# 欢迎框的宽度上限。Claude Code 的框不会铺满整个屏幕，留白反而更精致。
WIDTH = 72


def prompt_text() -> str:
    """生成输入提示符（带颜色）。

    为什么用原始颜色码而不是 rich？
      因为 input() 是 Python 内置函数，不接受 rich 对象，只能给它一段字符串。
      这里的 \\x1b[38;5;209m 是 256 色终端里最接近 Claude 橙的一个色号，
      比真彩色码兼容性更好（老一点的终端也认）。
    """
    return f"\x1b[38;5;209m{PROMPT}\x1b[0m "
