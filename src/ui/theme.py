# =============================================================================
# 文件：src/ui/theme.py
# 作用：整个界面的"配色和符号"都集中在这里
#
# 为什么单独搞一个文件？
#   之前颜色散落在各个文件里：有的用 print 打 emoji，有的用 rich 打颜色，
#   想统一风格就得改七八个地方。现在所有颜色、符号、缩进都从这一份定义里取。
#
# 【2026-11-07 第 10 轮】按 Claude Code 2.1.296 的实拍截图重做：
#   1. 圆点从 ⏺ 换成 ●
#      这是本轮最重要的一个字符改动。⏺ 是 U+23FA（BLACK CIRCLE FOR RECORD），
#      属于 Unicode 的"杂项符号"区，Windows Terminal / conhost 会把它交给
#      Segoe UI Emoji 去渲染 —— 结果是一个**彩色的、绿油油的 emoji 圆点**，
#      而且颜色不受 rich 控制（写 style="green" 也没用）。
#      它和橙色 ✻ 交替出现，看起来就是"橙绿交替一闪一闪"。
#      ● 是 U+25CF（BLACK CIRCLE），纯几何字符，永远按前景色渲染，
#      写绿就是绿、写白就是白 —— Claude Code 用的正是这个。
#   2. 助手/工具圆点统一为绿色（截图里两处都是绿点）
#   3. 新增欢迎页的方块 logo 与底部状态栏符号
# =============================================================================

from rich.console import Console  # rich 的控制台对象
from rich.theme import Theme  # 主题：给"样式名"起别名，后面用名字引用颜色

# --- 颜色 -------------------------------------------------------------------
# Claude Code 的配色非常克制：绝大多数文字是默认白/灰，只有三处上色：
#   圆点和 ✻ 标志 → 品牌橙或绿；成功/新增 → 绿；失败/删除 → 红
ACCENT = "rgb(217,119,87)"  # Claude 品牌橙 #D97757，用于 ✻ 和输入提示符
DIM = "bright_black"  # 次要信息：路径、参数、状态行
OK = "green"  # 成功 / 助手圆点
ERR = "red"  # 失败
WARN = "yellow"  # 警告（只在上文快满时用）
BULLET_COLOR = "green"  # 【第 10 轮】● 的颜色，对齐截图里的绿色实心圆

# --- 符号 -------------------------------------------------------------------
# 这几个符号是 Claude Code 的辨识度所在，别随便换：
BULLET = "●"  # 模型发言 / 工具调用的起始标记（U+25CF，纯文本字符，颜色可控）
RESULT = "⎿"  # 结果的转折标记
PROMPT = ">"  # 输入提示符（Claude Code 用的是 >）
STAR = "✻"  # 品牌标志 / 等待动画
CHECK_ON = "✔"  # 已完成
CHECK_OFF = "◻"  # 未完成
CHECK_RUN = "◼"  # 进行中
CROSS = "✗"  # 失败
DOT = "·"  # 分隔点
WARN_SIGN = "!"  # 警告标记（高危操作确认前提示用）
ARROWS = "▸▸"  # 【第 10 轮】底部状态栏的模式指示（截图左下角）

# 等待模型时的旋转图案。八帧循环，看起来像转轮在转。
# 【2026-11-08 第 18.2 轮：为什么从星芒换成盲文点转轮】
#   原来的四帧 ✻ ✢ ✳ ✶ 全落在 U+2700~27BF（Dingbats）emoji 区，
#   独立的 PowerShell / cmd（conhost）会优先用 emoji 字体把它们渲染成
#   "彩色（绿油油）的图案"，和橙色的 ✻ 交替出现，就是"橙绿交替闪"。
#   试过给每个字符加 U+FE0E（VS15 文本呈现选择器）强制单色，但 conhost
#   不支持 VS15，照样绿；只有 PyCharm 那种非真终端才不受影响。
#
#   盲文点 U+2800 区是唯一"任何终端都按前景色渲染、绝不会进 emoji 字体"
#   的转轮字符，这也是业界标准 spinner（很多 CLI 工具都用同一组）。
#   代价是它看起来是"转圈的点"，不是 Claude Code 那个饱满的星芒——
#   但在 conhost 里，"饱满星芒"和"单色橙色"本质是二选一，没有兼得。
#   如果将来换到支持 VS15 的终端（如 Windows Terminal），想换回星芒，
#   把这组换回 ["✻\uFE0E", "✢\uFE0E", "✳\uFE0E", "✶\uFE0E"] 即可。
SPIN_FRAMES = [
    "⠋", "⠙", "⠹", "⠸", "⠼", "⠴", "⠦", "⠧", "⠇", "⠏",
]

# 等待时的动词，每 3 秒换一个（2026-11-09 第 19 轮新增）。
# 为什么需要它：
#   只有一个"正在思考…"加秒数，看久了会让人怀疑是不是卡住了——秒数虽然在涨，
#   但它变化太慢（1 秒才跳一次）。动词轮换 + 省略号呼吸，能让人一眼看出
#   "它还在动"，不用盯着数字。
# 为什么是这几个词：都是"模型在干活"的中性说法，不带承诺（不说"马上好"），
#   也不会因为任务不同而显得驴唇不对马嘴。
WAIT_VERBS = ("正在思考", "正在分析", "正在推敲", "正在整理", "正在核对")

# 隐藏 / 恢复光标（2026-11-09 第 19 轮新增）。
# 为什么需要：
#   spinner 每帧要把整行补齐到固定宽度（否则短帧会留残影），补出来的空格
#   会把光标推到文字右侧很远的地方，于是等待期间屏幕上只有一个孤零零的方块
#   在空白里闪——看起来像"光标位置错了"，其实是补齐的副产物。
#   隐藏光标之后，视觉焦点自然落在转轮上，这是所有 CLI spinner 的标准做法。
# 必须成对使用：漏掉恢复，进程结束后那个终端就再也看不见光标了。
CURSOR_HIDE = "\x1b[?25l"
CURSOR_SHOW = "\x1b[?25h"

# 全局唯一的一个控制台对象。
# 之前每个类都 new 一个 Console，导致样式各写各的；现在大家共用这一个。
console = Console(
    theme=Theme({
        "qs.accent": ACCENT,
        "qs.dim": DIM,
        "qs.ok": OK,
        "qs.err": ERR,
        "qs.warn": WARN,
        "qs.bullet": BULLET_COLOR,
    }),
    highlight=False,  # 关掉自动高亮，避免把普通文字里的数字、路径染成奇怪的颜色
    # 关掉 safe_box：rich 默认在"看起来不像真终端"时用 ┌─┐ 代替圆角 ╭─╮，
    # 导致同一个界面在终端里是圆角、重定向到文件时变方角。这里统一成圆角。
    safe_box=False,
)

# 欢迎区的总宽度上限（去掉边框之后，只用于限制 logo + 文字的整体宽度感）
WIDTH = 72


def prompt_text() -> str:
    """生成输入提示符（带颜色）。

    为什么用原始颜色码而不是 rich？
      因为 input() 是 Python 内置函数，不接受 rich 对象，只能给它一段字符串。
      这里的 \\x1b[38;5;209m 是 256 色终端里最接近 Claude 橙的一个色号，
      比真彩色码兼容性更好（老一点的终端也认）。
    """
    return f"\x1b[38;5;209m{PROMPT}\x1b[0m "


# 【第 10 轮】等待动画不走 rich，而是直接往 stdout 写转义码。
# 原因见 display_manager._spin_loop 的说明：rich 的 Live 用"光标上移+覆盖"重绘，
# 不清行，高度一变就有残影。单行 spinner 必须能精确擦掉自己，所以手工控制。
ACCENT_ANSI = "\x1b[38;5;209m"  # 品牌橙（256 色）
DIM_ANSI = "\x1b[38;5;244m"  # 暗灰（256 色）
RESET_ANSI = "\x1b[0m"
CLEAR_LINE = "\r\x1b[2K"  # 回车 + 清整行，单行重绘的标准写法


def dim_text(text: str) -> str:
    """把一段文字染色成暗灰（给 input() 的提示文字用）

    和 prompt_text 同样的道理：input() 只认原始转义码。
    bright_black 在 256 色里是 244 号。
    """
    return f"\x1b[38;5;244m{text}\x1b[0m"


# =============================================================================
# 【2026-11-12 第 33 轮】四档工作模式的配色
#
# 【为什么分两套（rich 颜色名 + 原始 ANSI 码）】
#   底栏是用 rich 的 Text 画的，可以直接吃 "rgb(...)"；
#   而输入行里的提示（LineEditor）是自己往 stdout 写转义码的，
#   rich 的颜色对象没法塞进那里——两者不能互转，只能各存一份。
#   两套都放在这个文件里，是刻意的：配色只有一个出处，
#   别处想加一种颜色，改这里就够了，不会出现"底栏是浅绿、提示是亮绿"。
#
# 【颜色怎么定的】
#   灰（default）：中性，不抢注意力，它是最常用的那一档。
#   浅绿（plan）：绿色在终端里天然表示"安全/只读"，和"只看不改"对得上。
#   紫（accept）：介于"中性"和"放行"之间，既能和灰区分，又不至于像红色那样刺眼。
#   金黄（auto）：最亮、最扎眼的一档。它对应"全放开、不再询问"，
#     必须让人一眼看到自己正处在这个状态——这是全套配色里唯一带警示意味的。
#
# 【16 色终端会降级成什么】
#   rgb 值在只认 16 色的 conhost 上会被 rich 降到最接近的标准色：
#   浅绿 → green、紫 → magenta、金黄 → yellow、灰 → bright_black。
#   四档仍然能分辨，不会出现"两个模式一个颜色"。
# =============================================================================
MODE_COLORS = {
    "default": DIM,  # 灰：沿用全项目统一的次要信息色
    "plan": "rgb(152,202,138)",  # 浅绿
    "accept": "rgb(160,130,220)",  # 紫
    "auto": "rgb(230,180,60)",  # 金黄
}

# 原始 ANSI 版本（256 色），给 LineEditor 那种直接写 stdout 的地方用。
# 色号说明：120 是浅绿、141 是中紫、220 是金黄、244 是暗灰。
MODE_ANSI = {
    "default": DIM_ANSI,
    "plan": "\x1b[38;5;120m",
    "accept": "\x1b[38;5;141m",
    "auto": "\x1b[38;5;220m",
}


def mode_color(mode: str) -> str:
    """取某一档的 rich 颜色，未知模式退回灰色（2026-11-12 第 33 轮新增）

    为什么兜底而不是抛异常：这个函数在画底栏的热路径上，
    一个拼错的状态值不该让整轮对话崩掉，显示成灰色最多是不好看。
    """
    return MODE_COLORS.get(mode, DIM)


def mode_ansi(mode: str, text: str) -> str:
    """把一段文字染成该模式的颜色（2026-11-12 第 33 轮新增）

    返回带转义码的完整字符串，调用方直接写 stdout 即可。末尾一律带复位码，
    否则后面所有输出都会沿用这个颜色（第 16.1 轮的同类教训）。
    """
    return f"{MODE_ANSI.get(mode, DIM_ANSI)}{text}\x1b[0m"
