# =============================================================================
# 文件：src/ui/theme.py
# 作用：整个界面的"配色和符号"都集中在这里
#
# 为什么单独搞一个文件？
#   之前颜色散落在各个文件里：有的用 print 打 emoji，有的用 rich 打颜色，
#   想统一风格就得改七八个地方。现在所有颜色、符号、缩进都从这一份定义里取。
#
# 【2026-11-07 第 10 轮】按 Claude Code 2.1.296 的实拍截图重做：
#   1. 圆点从 ⏺ 换成 ●
#      这是本轮最重要的一个字符改动。⏺ 是 U+23FA（BLACK CIRCLE FOR RECORD），
#      属于 Unicode 的"杂项符号"区，Windows Terminal / conhost 会把它交给
#      Segoe UI Emoji 去渲染 —— 结果是一个**彩色的、绿油油的 emoji 圆点**，
#      而且颜色不受 rich 控制（写 style="green" 也没用）。
#      它和橙色 ✻ 交替出现，看起来就是"橙绿交替一闪一闪"。
#      ● 是 U+25CF（BLACK CIRCLE），纯几何字符，永远按前景色渲染，
#      写绿就是绿、写白就是白 —— Claude Code 用的正是这个。
#   2. 助手/工具圆点统一为绿色（截图里两处都是绿点）
#   3. 新增欢迎页的方块 logo 与底部状态栏符号
# =============================================================================

from rich.console import Console  # rich 的控制台对象
from rich.theme import Theme  # 主题：给"样式名"起别名，后面用名字引用颜色

# --- 颜色 -------------------------------------------------------------------
# Claude Code 的配色非常克制：绝大多数文字是默认白/灰，只有三处上色：
#   圆点和 ✻ 标志 → 品牌橙或绿；成功/新增 → 绿；失败/删除 → 红
ACCENT = "rgb(217,119,87)"  # Claude 品牌橙 #D97757，用于 ✻ 和输入提示符
DIM = "bright_black"  # 次要信息：路径、参数、状态行
OK = "green"  # 成功 / 助手圆点
ERR = "red"  # 失败
WARN = "yellow"  # 警告（只在上文快满时用）
BULLET_COLOR = "green"  # 【第 10 轮】● 的颜色，对齐截图里的绿色实心圆

# --- 符号 -------------------------------------------------------------------
# 这几个符号是 Claude Code 的辨识度所在，别随便换：
BULLET = "●"  # 模型发言 / 工具调用的起始标记（U+25CF，纯文本字符，颜色可控）
RESULT = "⎿"  # 结果的转折标记
PROMPT = ">"  # 输入提示符（Claude Code 用的是 >）
STAR = "✻"  # 品牌标志 / 等待动画
CHECK_ON = "✔"  # 已完成
CHECK_OFF = "◻"  # 未完成
CHECK_RUN = "◼"  # 进行中
CROSS = "✗"  # 失败
DOT = "·"  # 分隔点
WARN_SIGN = "!"  # 警告标记（高危操作确认前提示用）
ARROWS = "▸▸"  # 【第 10 轮】底部状态栏的模式指示（截图左下角）

# 等待模型时的旋转图案。四帧循环，看起来像星芒在转。
# 注意：这四帧都是同一个字符家族的纯文本符号，不会触发 emoji 渲染。
SPIN_FRAMES = ["✻", "✢", "✳", "✶"]

# 欢迎页左侧的方块 logo（4 行，每行等宽）。
# 为什么用 █ 和 ▄▀ 而不是图片？
#   终端只能放字符。半块字符 ▄▀ 能画出"边缘"，比清一色 █ 更像一个有形状的图标。
LOGO_LINES = [
    "▄▄▄▄▄▄▄  ▄▄▄▄▄▄",
    "███████  ██████",
    "███████  ██████",
    "▀▀▀▀▀▀▀  ▀▀▀▀▀▀",
]
LOGO_WIDTH = len(LOGO_LINES[0])  # 后面排版要用：logo 占多少列
LOGO_GAP = 4  # logo 和右侧文字之间空几格

# 全局唯一的一个控制台对象。
# 之前每个类都 new 一个 Console，导致样式各写各的；现在大家共用这一个。
console = Console(
    theme=Theme({
        "qs.accent": ACCENT,
        "qs.dim": DIM,
        "qs.ok": OK,
        "qs.err": ERR,
        "qs.warn": WARN,
        "qs.bullet": BULLET_COLOR,
    }),
    highlight=False,  # 关掉自动高亮，避免把普通文字里的数字、路径染成奇怪的颜色
    # 关掉 safe_box：rich 默认在"看起来不像真终端"时用 ┌─┐ 代替圆角 ╭─╮，
    # 导致同一个界面在终端里是圆角、重定向到文件时变方角。这里统一成圆角。
    safe_box=False,
)

# 欢迎区的总宽度上限（去掉边框之后，只用于限制 logo + 文字的整体宽度感）
WIDTH = 72


def prompt_text() -> str:
    """生成输入提示符（带颜色）。

    为什么用原始颜色码而不是 rich？
      因为 input() 是 Python 内置函数，不接受 rich 对象，只能给它一段字符串。
      这里的 \\x1b[38;5;209m 是 256 色终端里最接近 Claude 橙的一个色号，
      比真彩色码兼容性更好（老一点的终端也认）。
    """
    return f"\x1b[38;5;209m{PROMPT}\x1b[0m "


# 【第 10 轮】等待动画不走 rich，而是直接往 stdout 写转义码。
# 原因见 display_manager._spin_loop 的说明：rich 的 Live 用"光标上移+覆盖"重绘，
# 不清行，高度一变就有残影。单行 spinner 必须能精确擦掉自己，所以手工控制。
ACCENT_ANSI = "\x1b[38;5;209m"  # 品牌橙（256 色）
DIM_ANSI = "\x1b[38;5;244m"  # 暗灰（256 色）
RESET_ANSI = "\x1b[0m"
CLEAR_LINE = "\r\x1b[2K"  # 回车 + 清整行，单行重绘的标准写法


def dim_text(text: str) -> str:
    """把一段文字染色成暗灰（给 input() 的提示文字用）

    和 prompt_text 同样的道理：input() 只认原始转义码。
    bright_black 在 256 色里是 244 号。
    """
    return f"\x1b[38;5;244m{text}\x1b[0m"
