# 文件：src/tools/skill/__init__.py
# 作用：技能子包的门牌（第 21 轮新增）。
#
# 这里面只有三样东西，和 tools/subagent/ 保持同一形状：
#   frontmatter.py  —— 解析 SKILL.md 头部那几个字段（故意写得很笨，不引 pyyaml）
#   skill_spec.py   —— 一份技能的字段 + 「正文怎么渲染」
#   skill_manager.py—— 扫目录、去重、优先级、给模型看的清单
#
# 为什么放在 tools/skill/ 而不是新建 src/skills/：
#   读者已经习惯了"数据类 + 管理器 + 一个工具入口"这套目录约定（见 tools/subagent/），
#   为技能另开一套只会让人多记一个位置。工具入口 skill_tool.py 放在 tools/ 下、
#   和 task.py 平级，是因为它就是一个普通工具。
#
# 这个文件故意留空：没有需要在包初始化时执行的逻辑。
# 有初始化逻辑的包会在 import 期做 IO（扫目录、读文件），而 import 期是
# 最不该出岔子的时刻——启动失败时用户连界面都看不到，只能看堆栈。
