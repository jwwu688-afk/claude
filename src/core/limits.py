# =============================================================================
# 文件：src/core/limits.py
# 作用："喂给模型的输出上限"只在这里定义一次，其他地方一律 import。
#
# 【为什么要有这个文件】（2026-11-06 第 9 轮）
#   原来同一个数字被定义了两遍：
#     cmd_runner.py       MAX_OUTPUT_CHARS = 30000     ← 工具自己先砍一刀
#     conversation.py     MAX_TOOL_OUTPUT_CHARS = 12000 ← 写进历史前又砍一刀
#   结果 30000 那一刀等于白写：输出刚到 30000，进对话历史时又被砍到 12000。
#   更难受的是 file_read：一次读 2000 行（约 15~20k 字符）本来读全了，
#   也会在写进历史时被腰斩，模型只能反复调整 offset 重读，反而多花钱。
#
# 【现在的规则】
#   1. 工具自己可以设更严格的上限（比如 file_read 的 2000 行），那是"业务上限"；
#   2. MAX_TOOL_OUTPUT_CHARS 是"兜底上限"，只负责拦住异常巨大的输出；
#   3. 兜底上限必须 >= 任何一个业务上限，否则业务上限就是假的。
#
# 【用环境变量改】
#   MAX_TOOL_OUTPUT_CHARS=30000  （默认 30000，约相当于 1 万 token 的中文）
# =============================================================================

import os  # 读环境变量


def _int_env(name: str, default: int, minimum: int = 1000) -> int:
    """从环境变量读一个整数，读不出来或明显不合理就用默认值

    为什么要有 minimum？
      如果谁手滑写成 MAX_TOOL_OUTPUT_CHARS=10，工具结果会被砍成两三个字，
      模型完全没法干活，而且这种错很难看出来。这里兜住下限。
    """
    raw = os.getenv(name)
    if raw is None or not str(raw).strip():  # 没配
        return default
    try:
        value = int(str(raw).strip())
    except (TypeError, ValueError):  # 配了个 "abc"
        return default
    return max(minimum, value)


# 单条工具输出写进对话历史时的兜底上限（字符数）
MAX_TOOL_OUTPUT_CHARS = _int_env("MAX_TOOL_OUTPUT_CHARS", 30000)


# -----------------------------------------------------------------------------
# 【2026-11-09 五层压缩第 3 批】L3 Microcompact 的"折叠阈值"（字符数）
#
# 为什么要有这个值？
#   工具输出刚写进历史时，允许它最宽到 MAX_TOOL_OUTPUT_CHARS（30000）。
#   但对话变长、上下文吃紧后，这些"早就被模型消费过的大块输出"最该被压。
#   L3 会把「较早的、可重复查询工具（file_read/file_grep 等读操作）的结果」
#   折叠成一句极简占位（中文）："[更早的工具结果已折叠，需要完整内容时请重新运行对应工具。]"
#   让模型知道"这条结果被折叠过、需要就重跑那个工具"。
#
#   但这个值不再是"压到多少"，而是"超过多少才值得折叠"的阈值：
#   一条工具结果只有超过 8000 字符，折叠才有明显收益；小于 8000 的，
#   折叠掉省不了几个 token，还平白丢了信息，不如原样留着。
#
# 为什么折叠成"整句占位"而不是"压到 8000 字摘要"？
#   这是对齐 Claude Code 的做法：可重复查询的工具重跑成本极低、还能拿到
#   "更新鲜"的结果，所以折叠成一句"重跑即可"完全无损，没必要保留摘要。
#   保留 8000 字摘要反而是"既占空间、又可能过时"——两头不讨好。
# -----------------------------------------------------------------------------
MICROCOMPACT_TOOL_OUTPUT_CHARS = _int_env("MICROCOMPACT_TOOL_OUTPUT_CHARS", 8000)


# -----------------------------------------------------------------------------
# 【2026-11-10 第 21 轮·技能机制】四个和「技能」有关的上限，集中放这里
#
# 为什么全放 limits.py：这一轮有四处截断（正文、描述、清单条数、清单总长），
# 散在 skill_spec / skill_manager 里各写一个数字，下一个人调大其中一个，
# 另外三个不会跟着动，"技能加载不全"这类问题就再也说不清是哪一刀砍的。
# -----------------------------------------------------------------------------

# 单份技能正文写进对话历史时的上限（字符数）。
#   为什么是 20000：它必须**低于** MAX_TOOL_OUTPUT_CHARS(30000)。
#   技能正文是作为工具结果（或用户消息）进历史的，出去还要过
#   Conversation._truncate_tool_output 那一刀。业务上限比兜底上限还高的话，
#   业务上限就是假的——第 9 轮已经为同一个坑改过一次（cmd_runner 30000 vs 12000）。
#   20000 字符约等于 6000~7000 个汉字，一份写得非常细的操作手册也就这个量级。
MAX_SKILL_BODY_CHARS = _int_env("MAX_SKILL_BODY_CHARS", 20000)

# 技能描述进「工具说明书」时的上限（字符数）。
#   为什么是 300 而不是 Claude Code 的 1536：
#     工具的 description 字段**每一轮请求都要发**。10 个技能 × 1536 字符
#     ≈ 每轮白烧 4000 字符，而模型判断"这个技能对不对得上"看第一句话就够。
#     这和子 agent 的 MAX_DESCRIPTION_CHARS = 160 是同一个取舍，
#     技能留得宽一些，因为描述里往往要带触发词（"pdf/论文/发票"）。
MAX_SKILL_DESCRIPTION_CHARS = _int_env("MAX_SKILL_DESCRIPTION_CHARS", 300)

# 工具说明书里最多列多少个技能。
#   50 × 120 token ≈ 6000 token / 轮。超过这个量，说明书就成了第二份系统提示词，
#   而模型的注意力是有限的——宁可让它少知道几个，也不要让清单淹没它。
MAX_SKILLS_IN_BLOCK = _int_env("MAX_SKILLS_IN_BLOCK", 50, minimum=1)

# 工具说明书里「可用技能」整块的上限（字符数）。
#   条数上限挡不住"每条都很长"的情况，所以再加一道总长上限。
#   【第 21.6 轮】6000 → 9000：实测导入 5 个学术技能后共 25 个，
#   25 × 300 字符 ≈ 7500，6000 的上限会把排在后面的 5 个技能整个挤掉——
#   "装了但模型看不见"比多花一点 token 更糟。9000 ≈ 3000 token/轮，
#   是 25 个技能全可见的代价；技能再往上加就该删而不是再调大这个数。
MAX_SKILLS_BLOCK_CHARS = _int_env("MAX_SKILLS_BLOCK_CHARS", 9000)
